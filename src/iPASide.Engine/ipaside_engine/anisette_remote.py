"""Anisette headers from a remote Mac service, using the community "v3" protocol.

Why this exists. Anisette is the device-provisioning data Apple's sign-in requires. iPASide used
to generate it on this PC by running Apple's Android libraries in an emulator. Since 2026-10-12
Apple has been closing that route in steps: first it rejected the Mac identity those libraries were
reported under (``-80045``), then it started refusing the final token request for a Windows
identity too (``-80046``). Apple wants anisette generated by Apple's real macOS or Windows
libraries, which cannot be run here. Every other open-source sideloader reached the same point and
moved to the same fix: iloader and xtool default to ``mac-ani.jkcoxson.com``, and SideStore ships it
in its official server list alongside two other Mac servers. This module speaks the same protocol
(``SideStore/omnisette-server``, "v3").

How it works, and what the service learns:

* Each install makes its own random 16-byte identifier and provisions it once. The service relays
  Apple's two provisioning steps (``startMachineProvisioning`` and ``finishMachineProvisioning``):
  iPASide talks to Apple directly and passes only the opaque ``spim``/``cpim``/``ptm``/``tk`` blobs
  through the service's WebSocket. The service answers with an opaque ``adi_pb`` blob that iPASide
  keeps in its data folder.
* After that, a plain HTTPS request with the identifier and ``adi_pb`` returns a fresh one-time
  password per Apple request. This is a per-install identity, not one shared by every user.
* The service never receives an Apple ID, a password, a verification code, a session token, a
  pairing record or any file. It can see the connecting IP address, the random identifier and those
  opaque blobs. All connections verify TLS.
* Apple's sign-in itself (SRP, two-factor, tokens, developer services) still goes straight from
  this PC to Apple, exactly as before.

Three servers are tried in order, so one volunteer-run service being down does not stop sign-in.
Everything a server sends back is validated before it is used.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
import plistlib
import re
import socket
import ssl
import time
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable
from urllib.parse import urlparse

import requests
from wsproto import ConnectionType, WSConnection
from wsproto.events import (
    AcceptConnection,
    BytesMessage,
    CloseConnection,
    Ping,
    RejectConnection,
    Request,
    TextMessage,
)

from . import paths, tls
from .anisette import AnisetteError

#: Mac anisette servers, tried in this order. These are the Mac servers iloader lists and SideStore's
#: official server list carries (the Windows ones are flaky and cannot do SMS two-factor).
SERVERS: tuple[str, ...] = (
    "https://mac-ani.jkcoxson.com",
    "https://new.ani.sidestore.io",
    "https://ani3.stikstore.app",
)

#: Set to one server URL to use only that one (for a self-hosted server, or to test).
SERVER_ENV = "IPASIDE_ANISETTE_SERVER"

STATE_FILE = "remote-v3.json"
_USER_AGENT = "iPASide"
_HTTP_TIMEOUT = 20.0
_WS_TIMEOUT = 30.0
_PROVISIONING_DEADLINE = 90.0
_CLIENT_INFO_TTL = 900.0
_MAX_FIELD = 8192

_CLIENT_INFO_RE = re.compile(r"^<[^<>\r\n]{1,100}> <[^<>\r\n]{1,100}> <[^<>\r\n]{1,160}>$")
_USER_AGENT_RE = re.compile(r"^[ -~]{1,160}$")
_PLIST_PROLOG = (
    b'<?xml version="1.0" encoding="UTF-8"?>\n'
    b'<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
    b'"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
)
_DEFAULT_START_URL = "https://gsa.apple.com/grandslam/MidService/startMachineProvisioning"
_DEFAULT_FINISH_URL = "https://gsa.apple.com/grandslam/MidService/finishMachineProvisioning"
_BAG_URL = "https://gsa.apple.com/grandslam/GsService2/lookup"


class _Unavailable(Exception):
    """This server could not be used (network, timeout, bad reply). The next one is tried."""


@dataclass(frozen=True)
class ClientIdentity:
    """The device identity a server says its anisette data belongs to."""

    client_info: str
    user_agent: str


@dataclass(frozen=True)
class Fetched:
    headers: dict[str, str]
    identity: ClientIdentity
    server: str


@dataclass
class _State:
    identifier: bytes
    adi_pb: bytes | None = None

    @classmethod
    def new(cls) -> _State:
        return cls(identifier=os.urandom(16))

    @property
    def md_lu(self) -> str:
        return hashlib.sha256(self.identifier).hexdigest()

    @property
    def device_id(self) -> str:
        return str(uuid.UUID(bytes=self.identifier))

    @property
    def identifier_b64(self) -> str:
        return base64.b64encode(self.identifier).decode("ascii")


# --------------------------------------------------------------------------- #
# A small synchronous WebSocket client (wsproto does the protocol; this does the I/O)
# --------------------------------------------------------------------------- #
class _WebSocket:
    def __init__(self, url: str, timeout: float) -> None:
        parsed = urlparse(url)
        secure = parsed.scheme == "wss"
        host = parsed.hostname or ""
        port = parsed.port or (443 if secure else 80)
        target = parsed.path or "/"
        if parsed.query:
            target += "?" + parsed.query
        try:
            raw = socket.create_connection((host, port), timeout=timeout)
        except OSError as exc:
            raise _Unavailable(f"cannot connect ({exc})") from exc
        try:
            if secure:
                context = ssl.create_default_context(cafile=tls.ca_bundle())
                raw = context.wrap_socket(raw, server_hostname=host)
        except (ssl.SSLError, OSError) as exc:
            raw.close()
            raise _Unavailable(f"TLS failed ({exc})") from exc
        self._sock = raw
        self._ws = WSConnection(ConnectionType.CLIENT)
        try:
            self._write(
                self._ws.send(
                    Request(
                        host=parsed.netloc,
                        target=target,
                        extra_headers=[(b"user-agent", _USER_AGENT.encode("ascii"))],
                    )
                )
            )
            self._await_accept(timeout)
        except Exception:
            self.close()
            raise

    def _write(self, data: bytes) -> None:
        try:
            self._sock.sendall(data)
        except OSError as exc:
            raise _Unavailable(f"connection lost ({exc})") from exc

    def _read(self, deadline: float) -> bytes:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise _Unavailable("timed out")
        self._sock.settimeout(remaining)
        try:
            return self._sock.recv(65536)
        except (socket.timeout, TimeoutError) as exc:
            raise _Unavailable("timed out") from exc
        except OSError as exc:
            raise _Unavailable(f"connection lost ({exc})") from exc

    def _await_accept(self, timeout: float) -> None:
        deadline = time.monotonic() + timeout
        while True:
            for event in self._ws.events():
                if isinstance(event, AcceptConnection):
                    return
                if isinstance(event, RejectConnection):
                    raise _Unavailable(f"refused the WebSocket (HTTP {event.status_code})")
            data = self._read(deadline)
            if not data:
                raise _Unavailable("closed during the WebSocket handshake")
            self._receive(data)

    def _receive(self, data: bytes) -> None:
        try:
            self._ws.receive_data(data)
        except Exception as exc:  # noqa: BLE001 - wsproto raises its own protocol errors
            raise _Unavailable(f"invalid WebSocket data ({exc})") from exc

    def send_text(self, text: str) -> None:
        self._write(self._ws.send(TextMessage(data=text)))

    def recv_text(self, timeout: float) -> str | None:
        """The next text message, or None once the server closed the connection."""
        deadline = time.monotonic() + timeout
        buffer = ""
        while True:
            for event in self._ws.events():
                if isinstance(event, TextMessage):
                    buffer += event.data
                    if len(buffer) > 4 * _MAX_FIELD:
                        raise _Unavailable("reply too large")
                    if event.message_finished:
                        return buffer
                elif isinstance(event, BytesMessage):
                    continue
                elif isinstance(event, Ping):
                    self._write(self._ws.send(event.response()))
                elif isinstance(event, CloseConnection):
                    try:
                        self._write(self._ws.send(event.response()))
                    except _Unavailable:
                        pass
                    return None
            data = self._read(deadline)
            if not data:
                return None
            self._receive(data)

    def close(self) -> None:
        try:
            self._sock.close()
        except OSError:
            pass


def _connect_websocket(url: str, timeout: float) -> _WebSocket:
    return _WebSocket(url, timeout)


# --------------------------------------------------------------------------- #
# State on disk
# --------------------------------------------------------------------------- #
def _state_path() -> Path:
    return paths.anisette_dir() / STATE_FILE


def _load_state() -> _State:
    try:
        raw = json.loads(_state_path().read_text(encoding="utf-8"))
        identifier = base64.b64decode(raw["identifier"], validate=True)
        if len(identifier) != 16:
            raise ValueError("identifier length")
        adi = raw.get("adi_pb")
        return _State(identifier, base64.b64decode(adi, validate=True) if adi else None)
    except Exception:  # noqa: BLE001 - missing or damaged: start a fresh identity
        return _State.new()


def _save_state(state: _State, server: str) -> None:
    payload = {
        "identifier": state.identifier_b64,
        "adi_pb": base64.b64encode(state.adi_pb).decode("ascii") if state.adi_pb else None,
        "server": server,
    }
    path = _state_path()
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(payload), encoding="utf-8")
    temporary.replace(path)


def reset_state() -> None:
    """Forget the provisioned identity; the next sign-in provisions a new one."""
    _state_path().unlink(missing_ok=True)


# --------------------------------------------------------------------------- #
# Validation of everything a server sends
# --------------------------------------------------------------------------- #
def _valid_server_url(url: str) -> bool:
    parsed = urlparse(url)
    if parsed.scheme == "https" and parsed.hostname:
        return True
    # Plain HTTP only to this machine, so a test server needs no certificate.
    return parsed.scheme == "http" and parsed.hostname in ("127.0.0.1", "localhost", "::1")


def _clean_header_value(name: str, value: Any) -> str:
    if not isinstance(value, str) or not value or len(value) > _MAX_FIELD or "\r" in value or "\n" in value:
        raise _Unavailable(f"the server's {name} was not a valid header value")
    return value


def _parse_identity(raw: Any) -> ClientIdentity:
    if not isinstance(raw, dict):
        raise _Unavailable("client_info was not a JSON object")
    info, agent = raw.get("client_info"), raw.get("user_agent")
    if not isinstance(info, str) or not _CLIENT_INFO_RE.fullmatch(info) or not info.isascii():
        raise _Unavailable("client_info was not in the expected form")
    if not isinstance(agent, str) or not _USER_AGENT_RE.fullmatch(agent):
        raise _Unavailable("user_agent was not in the expected form")
    return ClientIdentity(info, agent)


def _loads_plist(raw: bytes) -> dict[str, Any]:
    try:
        parsed = plistlib.loads(raw)
    except Exception:  # noqa: BLE001 - Apple omits the XML prolog on some replies
        parsed = plistlib.loads(_PLIST_PROLOG + raw)
    if not isinstance(parsed, dict):
        raise ValueError("not a dictionary")
    return parsed


# --------------------------------------------------------------------------- #
# The provider
# --------------------------------------------------------------------------- #
class RemoteAnisette:
    def __init__(
        self,
        servers: tuple[str, ...] | None = None,
        *,
        connect: Callable[[str, float], Any] = _connect_websocket,
    ) -> None:
        self._servers = servers
        self._connect = connect
        self._identity: dict[str, tuple[float, ClientIdentity]] = {}

    # -- servers ------------------------------------------------------------ #
    def servers(self) -> tuple[str, ...]:
        if self._servers is not None:
            return self._servers
        override = os.environ.get(SERVER_ENV, "").strip().rstrip("/")
        if override:
            if not _valid_server_url(override):
                raise AnisetteError(
                    f"{SERVER_ENV} must be an https:// address (got {override!r})."
                )
            return (override,)
        return SERVERS

    def fetch(self) -> Fetched:
        """Fresh anisette headers, provisioning this install first if it has no identity yet."""
        failures: list[str] = []
        for server in self.servers():
            try:
                return self._fetch_from(server)
            except _Unavailable as exc:
                failures.append(f"{urlparse(server).hostname}: {exc}")
        raise AnisetteError(
            "Could not reach any anisette service, which Apple's sign-in needs. Check your "
            "internet connection and try again in a few minutes.\n\nTried:\n  "
            + "\n  ".join(failures)
        )

    def _fetch_from(self, server: str) -> Fetched:
        identity = self._client_identity(server)
        state = _load_state()
        if state.adi_pb is None:
            self._provision(server, identity, state)
        try:
            return self._headers(server, identity, state)
        except _NeedsProvisioning:
            fresh = _State.new()
            self._provision(server, identity, fresh)
            try:
                return self._headers(server, identity, fresh)
            except _NeedsProvisioning:
                raise AnisetteError(
                    "The anisette service rejected a freshly provisioned identity. Try again "
                    "later; if it keeps happening, report it with %LOCALAPPDATA%\\iPASide\\gsa-trace.log."
                ) from None

    # -- client identity -------------------------------------------------------- #
    def _client_identity(self, server: str) -> ClientIdentity:
        cached = self._identity.get(server)
        if cached and time.monotonic() - cached[0] < _CLIENT_INFO_TTL:
            return cached[1]
        data = self._get_json(f"{server}/v3/client_info")
        identity = _parse_identity(data)
        self._identity[server] = (time.monotonic(), identity)
        return identity

    # -- HTTP -------------------------------------------------------------------- #
    def _get_json(self, url: str) -> Any:
        try:
            response = requests.get(
                url, timeout=_HTTP_TIMEOUT, headers={"User-Agent": _USER_AGENT}, verify=tls.ca_bundle()
            )
        except requests.RequestException as exc:
            raise _Unavailable(f"cannot connect ({type(exc).__name__})") from exc
        return self._json_body(response)

    def _post_json(self, url: str, body: dict[str, Any]) -> Any:
        try:
            response = requests.post(
                url,
                data=json.dumps(body),
                timeout=_HTTP_TIMEOUT,
                headers={"User-Agent": _USER_AGENT, "Content-Type": "application/json"},
                verify=tls.ca_bundle(),
            )
        except requests.RequestException as exc:
            raise _Unavailable(f"cannot connect ({type(exc).__name__})") from exc
        return self._json_body(response)

    @staticmethod
    def _json_body(response: requests.Response) -> Any:
        if response.status_code != 200:
            raise _Unavailable(f"answered HTTP {response.status_code}")
        try:
            return response.json()
        except ValueError as exc:
            raise _Unavailable("did not answer with JSON") from exc

    # -- headers ----------------------------------------------------------------- #
    def _headers(self, server: str, identity: ClientIdentity, state: _State) -> Fetched:
        assert state.adi_pb is not None
        data = self._post_json(
            f"{server}/v3/get_headers",
            {"identifier": state.identifier_b64, "adi_pb": base64.b64encode(state.adi_pb).decode("ascii")},
        )
        if not isinstance(data, dict):
            raise _Unavailable("get_headers did not return an object")
        result = data.get("result")
        if result == "GetHeadersError":
            message = str(data.get("message", ""))
            if "-45061" in message:
                raise _NeedsProvisioning
            raise AnisetteError(f"The anisette service could not make headers: {message[:300]}")
        if result != "Headers":
            raise _Unavailable("get_headers returned an unknown result")
        headers = {
            "X-Apple-I-Client-Time": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "X-Apple-I-MD": _clean_header_value("X-Apple-I-MD", data.get("X-Apple-I-MD")),
            "X-Apple-I-MD-LU": state.md_lu,
            "X-Apple-I-MD-M": _clean_header_value("X-Apple-I-MD-M", data.get("X-Apple-I-MD-M")),
            "X-Apple-I-MD-RINFO": _clean_header_value("X-Apple-I-MD-RINFO", data.get("X-Apple-I-MD-RINFO")),
            "X-Apple-I-SRL-NO": "0",
            "X-Mme-Device-Id": state.device_id,
        }
        return Fetched(headers=headers, identity=identity, server=server)

    # -- provisioning -------------------------------------------------------------- #
    def _provision(self, server: str, identity: ClientIdentity, state: _State) -> None:
        start_url, finish_url = self._provisioning_urls(identity)
        ws_url = server.replace("https://", "wss://", 1).replace("http://", "ws://", 1) + "/v3/provisioning_session"
        deadline = time.monotonic() + _PROVISIONING_DEADLINE
        socket_ = self._connect(ws_url, _WS_TIMEOUT)
        try:
            while True:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise _Unavailable("provisioning took too long")
                text = socket_.recv_text(remaining)
                if text is None:
                    raise _Unavailable("closed the provisioning connection early")
                try:
                    message = json.loads(text)
                except ValueError as exc:
                    raise _Unavailable("sent a provisioning message that was not JSON") from exc
                if not isinstance(message, dict):
                    raise _Unavailable("sent an unexpected provisioning message")
                result = message.get("result")
                if result == "GiveIdentifier":
                    socket_.send_text(json.dumps({"identifier": state.identifier_b64}))
                elif result == "GiveStartProvisioningData":
                    reply = self._apple_post(start_url, {"Header": {}, "Request": {}}, identity, state)
                    socket_.send_text(json.dumps({"spim": self._required(reply, "spim")}))
                elif result == "GiveEndProvisioningData":
                    cpim = _clean_header_value("cpim", message.get("cpim"))
                    reply = self._apple_post(finish_url, {"Header": {}, "Request": {"cpim": cpim}}, identity, state)
                    socket_.send_text(
                        json.dumps({"ptm": self._required(reply, "ptm"), "tk": self._required(reply, "tk")})
                    )
                elif result == "ProvisioningSuccess":
                    try:
                        state.adi_pb = base64.b64decode(str(message.get("adi_pb", "")), validate=True)
                    except ValueError as exc:
                        raise _Unavailable("returned an invalid identity blob") from exc
                    if not state.adi_pb:
                        raise _Unavailable("returned an empty identity blob")
                    _save_state(state, server)
                    return
                elif result == "Timeout":
                    raise _Unavailable("provisioning timed out on the server")
                elif result == "InvalidIdentifier":
                    raise _Unavailable("rejected the identifier")
                elif result in ("StartProvisioningError", "EndProvisioningError"):
                    raise AnisetteError(
                        "Apple's device provisioning failed ("
                        + ("start" if result == "StartProvisioningError" else "finish")
                        + f"): {str(message.get('message', ''))[:300]}"
                    )
                else:
                    raise _Unavailable("sent an unknown provisioning message")
        finally:
            socket_.close()

    @staticmethod
    def _required(reply: dict[str, Any], key: str) -> str:
        value = reply.get(key)
        if not isinstance(value, str) or not value or len(value) > 4 * _MAX_FIELD:
            raise AnisetteError(f"Apple's provisioning reply had no valid '{key}'.")
        return value

    def _provisioning_urls(self, identity: ClientIdentity) -> tuple[str, str]:
        """Apple's two provisioning URLs, from its URL bag, falling back to the known ones."""
        try:
            response = requests.get(
                _BAG_URL,
                headers={"X-MMe-Client-Info": identity.client_info, "User-Agent": identity.user_agent, "Accept": "*/*"},
                timeout=_HTTP_TIMEOUT,
                verify=tls.ca_bundle(),
            )
            bag = _loads_plist(response.content)
            urls = bag.get("urls", bag)
            start, finish = urls.get("midStartProvisioning"), urls.get("midFinishProvisioning")
            if _apple_url(start) and _apple_url(finish):
                return start, finish
        except Exception:  # noqa: BLE001 - the known URLs are the same today
            pass
        return _DEFAULT_START_URL, _DEFAULT_FINISH_URL

    def _apple_post(
        self, url: str, body: dict[str, Any], identity: ClientIdentity, state: _State
    ) -> dict[str, Any]:
        """One request to Apple's provisioning service, on its own connection."""
        if not _apple_url(url):
            raise AnisetteError("Apple's provisioning address was not an Apple address.")
        headers = {
            "Content-Type": "text/x-xml-plist",
            "Accept": "*/*",
            "Connection": "close",
            "User-Agent": identity.user_agent,
            "X-MMe-Client-Info": identity.client_info,
            "X-Apple-I-MD-LU": state.md_lu,
            "X-Mme-Device-Id": state.device_id,
        }
        try:
            with requests.Session() as session:
                response = session.post(
                    url, data=plistlib.dumps(body), headers=headers, timeout=_HTTP_TIMEOUT, verify=tls.ca_bundle()
                )
        except requests.RequestException as exc:
            raise AnisetteError(
                f"Could not reach Apple's provisioning service ({type(exc).__name__}). Check your connection."
            ) from exc
        if response.status_code != 200:
            raise AnisetteError(f"Apple's provisioning service answered HTTP {response.status_code}. Try again later.")
        try:
            parsed = _loads_plist(response.content)
        except Exception as exc:  # noqa: BLE001
            raise AnisetteError("Apple's provisioning service sent a reply that could not be read.") from exc
        reply = parsed.get("Response", parsed)
        if not isinstance(reply, dict):
            raise AnisetteError("Apple's provisioning service sent a reply that could not be read.")
        status = reply.get("Status", {})
        code = status.get("ec", 0) if isinstance(status, dict) else 0
        if code:
            raise AnisetteError(f"Apple's provisioning service answered error {code}: {status.get('em', '')}")
        return reply


class _NeedsProvisioning(Exception):
    """The service says this identity is not (or no longer) provisioned (-45061)."""


def _apple_url(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    parsed = urlparse(value)
    return parsed.scheme == "https" and (parsed.hostname or "").endswith(".apple.com")


_provider = RemoteAnisette()


def fetch() -> Fetched:
    """Fresh anisette headers from the remote service (see :class:`RemoteAnisette`)."""
    return _provider.fetch()
